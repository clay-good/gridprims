/** @param {string} s */
export const sha256 = (s) => createHash('sha256').update(s).digest('hex');

/**
 * @param {{outDir?: string, pseudo?: boolean}} [opts] pseudo renders every string in the pseudo-locale for the layout sweep
 * @returns {{outDir: string, pages: string[], files: number}}
 */
export async function build(opts = {}) {
  const outDir = opts.outDir ?? join(ROOT, 'dist');
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });
  for (const p of SHARED) cpSync(join(ROOT, p), join(outDir, p), { recursive: true, filter: (src) => !src.endsWith('README.md') });
  mkdirSync(join(outDir, 'site/styles'), { recursive: true });
  writeFileSync(join(outDir, 'site/styles/site.css'), STYLE_PARTS.map((f) => readFileSync(join(ROOT, f), 'utf8')).join('\n'));
  writeFileSync(join(outDir, 'site/styles/tokens.css'), tokensCss());
  // In the pseudo-locale the browser modules read pseudo strings too, so nothing re-renders in English.
  if (opts.pseudo) writeFileSync(join(outDir, 'site/strings/en-US.mjs'), `export default ${JSON.stringify(pseudoMessages(strings), null, 2)};\n`);
  // Built dataset versions ship with the site (foundation design D5, D16); curated records feed the build only.
  cpSync(join(ROOT, 'data'), join(outDir, 'data'), { recursive: true, filter: (src) => !src.endsWith('README.md') && !src.includes(`${'/'}curated`) && !src.includes(`${'/'}health`) });

  const i18n = createI18n(opts.pseudo ? pseudoMessages(strings) : strings, 'en-US');
  const pages = [];
  // The build's date is the commit's, never the wall clock (platform/privacy-and-security, supply-chain integrity).
  let buildDate = '2026-10-31T00:00:00Z';
  try { buildDate = execFileSync('git', ['log', '-1', '--format=%cI'], { cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim() || buildDate; } catch { /* not a git checkout */ }
  const healthFile = join(ROOT, 'data/health/pipeline.json');
  const health = existsSync(healthFile) ? JSON.parse(readFileSync(healthFile, 'utf8')) : null;
  // The grid pulse in every page's rail: the lower 48's latest daily peaks, from the EIA-930 rollups.
  const balancing = balancingPages(join(ROOT, 'data'));
  setPulse(balancing?.pulse ?? null);
  // Every page's title and description, checked once all are written (site/discoverability).
  const titles = new Map();
  const tooLong = [];
  const decode = (x) => x.replace(/&#39;/g, "'").replace(/&quot;/g, '"').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');
  const write = (path, html) => {
    const file = path.endsWith('/') ? join(outDir, path, 'index.html') : join(outDir, path);
    mkdirSync(dirname(file), { recursive: true });
    const text = String(html);
    writeFileSync(file, text);
    pages.push(path);
    if (!path.endsWith('/')) return;
    const title = decode(/<title>([^<]*)<\/title>/.exec(text)?.[1] ?? '');
    const description = decode(/<meta name="description" content="([^"]*)">/.exec(text)?.[1] ?? '');
    titles.set(title, [...(titles.get(title) ?? []), path]);
    // The pseudo-locale stretches text on purpose, so lengths are checked in the real locale only.
    if (!opts.pseudo && title.length > TITLE_MAX) tooLong.push(`${path}: title is ${title.length} characters`);
    if (!opts.pseudo && description.length > DESCRIPTION_MAX) tooLong.push(`${path}: description is ${description.length} characters`);
  };

  for (const tool of TOOLS) {
    const { manifest } = tool;
    if (manifest.archetype !== 'calculator') continue;
    const example = manifest.examples[0];
    const result = runTool(manifest, tool.impl, example.inputs);
    if (result.status !== 'ok') throw new Error(`${manifest.id}: first worked example returned ${result.status}`);
    write(toolPath(manifest.id), calculatorPage({ manifest, example, result, i18n }));
  }
  // The limits record: one object for the page, its JSON copy, and the MCP resource.
  const datasets = existsSync(join(ROOT, 'data')) ? readdirSync(join(ROOT, 'data')).filter((id) => existsSync(join(ROOT, 'data', id, 'current.json'))).map((id) => JSON.parse(readFileSync(join(ROOT, 'data', id, JSON.parse(readFileSync(join(ROOT, 'data', id, 'current.json'), 'utf8')).version, 'manifest.json'), 'utf8'))) : [];
  // Lateness is judged on the registry's cadence, which records what we know now (a decennial Census file,
  // say), not the copy each served version's manifest kept when it was cut.
  for (const m of datasets) {
    const reg = join(ROOT, 'pipeline/registry', `${m.dataset}.mjs`);
    if (existsSync(reg)) m.cadence = (await import(pathToFileURL(reg).href)).default.cadence ?? m.cadence;
  }
  let describes = null;
  try { describes = execFileSync('git', ['rev-parse', '--short', 'HEAD'], { cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim(); } catch { describes = null; }
  // The continuity ledger, as a page and as JSON, generated with the build's own date so pages age it on the
  // device. It is built here because the limits page reads its late, stalled, and dead-link rows from it.
  const ledger = buildLedger({ datasets: await ledgerDatasets(ROOT), health, replies: ledgerReplies, generatedAt: health?.generatedAt ?? buildDate, contact: `${ORIGIN}/report/` });
  const limits = limitsRecord({ tools: TOOLS, cannotDo, claims, health, ledger, generatedAt: health?.generatedAt ?? null, describes, now: Date.parse(health?.generatedAt ?? '2026-10-31T00:00:00Z') });
  write('/limits/', limitsPage({ limits, i18n, health }));
  if (health) { mkdirSync(join(outDir, 'health'), { recursive: true }); cpSync(healthFile, join(outDir, 'health/pipeline.json')); }
  writeFileSync(join(outDir, 'limits/limits.json'), JSON.stringify(limits, null, 2) + '\n');
  write('/changelog/', changelogPage({ entries: changelog, i18n }));
  write('/settings/', settingsPage({ i18n }));
  // Workbench capabilities carry "Review pending" until docs/review-signoffs.md has a row for them.
  const reviewedIds = new Set(tableRows(readFileSync(join(ROOT, 'docs/review-signoffs.md'), 'utf8')).keys());
  write('/files/', filesPage({ i18n, reviewed: reviewedIds }));
  write('/privacy/', privacyPage({ i18n }));
  write('/learn/get-your-data/', getYourDataPage({ i18n }));
  write('/developers/', developersPage({ i18n }));
  write('/security/', securityPage({ i18n }));
  // The trust page set (site/trust-pages).
  const signoffs = [...tableRows(readFileSync(join(ROOT, 'docs/review-signoffs.md'), 'utf8')).keys()].map((tool) => ({ tool }));
  const passed = new Map((health?.tools ?? []).map((x) => [x.id, x.evidencePassed]));
  write('/about/', aboutPage({ i18n, maintainer: MAINTAINER }));
  write('/methods/', methodsIndexPage({ tools: TOOLS, i18n }));
  for (const { manifest } of TOOLS) write(`/methods/${manifest.id}/`, methodsPage({ manifest, i18n, passed: passed.get(manifest.id) }));
  write('/accessibility/', accessibilityPage({ i18n }));
  write('/corrections/', correctionsPage({ entries: corrections, i18n }));
  const first = TOOLS[0];
  const firstResult = first && runTool(first.manifest, first.impl, first.manifest.examples[0].inputs);
  const example = first && { sentence: firstResult.sentence, title: first.manifest.title, version: first.manifest.version, url: `${ORIGIN}${toolPath(first.manifest.id)}#${new URLSearchParams(first.manifest.examples[0].inputs)}` };
  write('/license/', licensePage({ i18n, datasets, example, buildDay: buildDate.slice(0, 10) }));
  write('/sources/', sourcesPage({ tools: TOOLS, datasets, i18n }));
  write('/review-status/', reviewPage({ tools: TOOLS, signoffs, i18n }));
  write('/terms/', termsPage({ i18n }));
  write('/continuity/', continuityPage({ i18n, datasets, node: readFileSync(join(ROOT, '.node-version'), 'utf8').trim() }));
  for (const id of existsSync(join(ROOT, 'data')) ? readdirSync(join(ROOT, 'data')) : []) {
    const cur = join(ROOT, 'data', id, 'current.json');
    if (!existsSync(cur)) continue;
    const { version } = JSON.parse(readFileSync(cur, 'utf8'));
    const entry = (await import(pathToFileURL(join(ROOT, 'pipeline/registry', `${id}.mjs`)).href)).default;
    const termsRow = health?.datasets.find((d) => d.id === id)?.terms;
    // The posture in force: a takedown, then the latest terms check, then the registry (hand-set or derived from the terms).
    const posture = entry.takedown ? 'link' : termsRow?.posture ?? postureOf(entry).posture;
    // Every version folder, newest first, with its manifest's checksum for the citation.
    const versions = readdirSync(join(ROOT, 'data', id), { withFileTypes: true }).filter((d) => d.isDirectory() && /^\d{4}-\d{2}$/.test(d.name)).map((d) => d.name).sort().reverse();
    const shas = Object.fromEntries(versions.map((v) => [v, sha256(readFileSync(join(ROOT, 'data', id, v, 'manifest.json')))]));
    write(`/data/${id}/`, datasetPage({ manifest: { ...JSON.parse(readFileSync(join(ROOT, 'data', id, version, 'manifest.json'), 'utf8')), cadence: entry.cadence }, i18n, posture, termsRow, takedown: entry.takedown, entry, shas,
      versions: versions.map((v) => JSON.parse(readFileSync(join(ROOT, 'data', id, v, 'manifest.json'), 'utf8'))) }));
    // Each version's diff against the one before, kept for every version we hold.
    for (const v of versions) {
      const df = join(ROOT, 'data', id, v, 'diff.json');
      if (existsSync(df)) write(diffPath(id, v), diffPage({ diff: JSON.parse(readFileSync(df, 'utf8')), entry, i18n }));
    }
    // Under the link posture no values are published, so none of the dataset's files deploy.
    if (posture === 'link') rmSync(join(outDir, 'data', id), { recursive: true, force: true });
  }
  // Entity pages, one per plant that passes the content minimum (add-public-grid-data: plant pages).
  const plants = plantPages(join(ROOT, 'data'));
  const utilities = utilityPages(join(ROOT, 'data'));
  // The large-load request card's prefill: every utility's Form 714 peak, retail sales, and average home use.
  if (utilities) {
    mkdirSync(join(outDir, 'large-load'), { recursive: true });
    writeFileSync(join(outDir, 'large-load/utilities.json'), JSON.stringify({ license: 'CC BY 4.0', sources: { eia861: utilities.sources.eia861.version, ferc714: utilities.sources.ferc714?.release ?? utilities.sources.ferc714?.version ?? null }, utilities: largeLoadUtilities(utilities), regulators: Object.fromEntries(regulators.map((r) => [r.state, { name: r.name, docket: r.docket }])) }));
  }
  const withPage = new Set((utilities?.utilities ?? []).filter((u) => u.page).map((u) => u.id));
  const plantIds = new Set((plants?.plants ?? []).map((p) => p.id));
  // Titles must be unique: a shared name gets its state, then its id.
  const plantNames = uniqueNames((plants?.plants ?? []).map((p) => ({ key: p.id, name: p.name, state: p.state, id: p.id })), 'plant');
  const utilityNames = uniqueNames((utilities?.utilities ?? []).filter((u) => u.page).map((u) => ({ key: u.id, name: u.name, state: u.homeState, id: u.id })), 'utility');
  for (const plant of plants?.plants ?? []) write(plantPath(plant.id), plantPage({ plant, sources: plants.sources, i18n, titleName: plantNames.get(plant.id), utilityPath: (id) => (withPage.has(id) ? utilityPath(id) : null) }));
  // A published plant page that fell below the content minimum redirects to its state page
  // (site/home-and-navigation, "Removed page"). There can be thousands, more than the redirect
  // budget, so the Worker reads them from one map instead of one rule each.
  if (plants) {
    const published = JSON.parse(readFileSync(join(ROOT, 'data/curated/published-urls.json'), 'utf8'));
    const moved = {};
    for (const url of published) {
      const id = Number(/^\/plants\/(\d+)\/$/.exec(url)?.[1]);
      const state = plants.stateOf.get(id);
      if (id && !plantIds.has(id) && state) moved[id] = statePath(state);
    }
    writeFileSync(join(outDir, MOVED_PLANTS), JSON.stringify(moved));
  }
  const regions = utilities && regionPages(join(ROOT, 'data'), utilities.utilities);
  const plantsByState = Map.groupBy(plants?.plants ?? [], (p) => p.state);
  // Net metering on state and utility pages (add-program-fact-pages), with the rules linked, never restated.
  const netMetering = netMeteringData(join(ROOT, 'data'));
  const regulatorOf = (st) => regulators.find((r) => r.state === st) ?? null;
  const communitySolar = communitySolarData(join(ROOT, 'data'));
  for (const state of regions?.states ?? []) write(statePath(state.code), statePage({ state, sources: regions.sources, i18n, plants: plantsByState.get(state.code) ?? [],
    extra: html`${netMetering ? netMeteringSection({ data: netMetering.state(state.code), nm: netMetering.manifest, i18n, regulator: regulatorOf(state.code), state: state.code, stateName: state.name }) : ''}${communitySolar ? communitySolarSection({ data: communitySolar.state(state.code), manifest: communitySolar.manifest, i18n, stateName: state.name }) : ''}` }));
  for (const subregion of regions?.subregions ?? []) write(subregionPath(subregion.subregion), subregionPage({ subregion, sources: regions.sources, i18n }));
  // Balancing authority pages, from daily and monthly rollups of the EIA-930 hourly snapshot.
  if (balancing) {
    for (const region of balancing.regions) {
      const inRegion = (utilities?.utilities ?? []).filter((u) => u.page && u.baCodes?.includes(region.ba)).sort((a, b) => a.name.localeCompare(b.name));
      const regionPlants = (plants?.plants ?? []).filter((p) => p.baCode === region.ba).sort((a, b) => b.nameplateMw - a.nameplateMw || a.name.localeCompare(b.name));
      write(balancingPath(region.ba), balancingPage({ region, manifest: balancing.manifest, utilities: inRegion, plants: regionPlants, i18n }));
    }
  }
  // The standards template for the line checks, as CSV and as a workbook from the same rows (design D1).
  mkdirSync(join(outDir, 'lines'), { recursive: true });
  writeFileSync(join(outDir, 'lines/standards-template.csv'), templateCsv());
  writeFileSync(join(outDir, 'lines/standards-template.xlsx'), writeXlsx({ Standards: templateSheet() }));
  // The glossary, as a page and as data agents read with the same words.
  write(GLOSSARY_PATH, glossaryPage({ entries: GLOSSARY, tools: TOOLS, i18n }));
  writeFileSync(join(outDir, 'learn/glossary/glossary.json'), JSON.stringify({ license: 'CC BY 4.0', publisher: 'gridprims', note: 'Entries adapted from the EIA glossary (a public-domain U.S. government work) say so.', entries: GLOSSARY }, null, 2) + '\n');
  // The large-load terms table, its downloads, and the archived copies of every source it cites.
  // Freshness is judged on the health record's clock, as the limits page is, so a build is reproducible.
  const terms = termsData(ROOT, Date.parse(health?.generatedAt ?? '2026-10-31T00:00:00Z'));
  write(TERMS_PATH, largeLoadTermsPage({ data: terms, i18n }));
  mkdirSync(join(outDir, 'large-load/sources'), { recursive: true });
  writeFileSync(join(outDir, 'large-load/terms/terms.json'), JSON.stringify({ license: 'CC BY 4.0', publisher: 'gridprims', note: 'Each value credits its own primary sources.', entries: terms.entries }, null, 2) + '\n');
  writeFileSync(join(outDir, 'large-load/terms/terms.csv'), termsCsv(terms));
  for (const c of terms.captures) copyFileSync(join(ROOT, c), join(outDir, capturePath(c)));
  // The scenario model: every region's fleet and backtest, its page, its downloads, and the fit table.
  const scenarios = scenarioData(join(ROOT, 'data'));
  if (scenarios) {
    write(SCENARIO_INDEX, scenarioIndexPage({ data: scenarios, i18n }));
    const file = (path, text) => { mkdirSync(dirname(join(outDir, path)), { recursive: true }); writeFileSync(join(outDir, path), text); };
    file(`${SCENARIO_INDEX}fit.json`, JSON.stringify({ license: 'CC BY 4.0', year: scenarios.year, versions: scenarios.versions, regions: scenarios.regions.map((r) => ({ ba: r.ba, name: r.name, summary: r.fleet.summary, backtest: r.backtest, causes: r.causes, categories: r.categories, unmet: r.unmet })) }));
    for (const region of scenarios.regions) {
      write(scenarioPath(region.ba), scenarioPage({ region, year: scenarios.year, versions: scenarios.versions, i18n }));
      file(`${scenarioPath(region.ba)}fleet.json`, JSON.stringify({ license: 'CC BY 4.0', attribution: 'Derived by gridprims from U.S. Energy Information Administration Forms EIA-860 and EIA-923.', ba: region.ba, name: region.name, zone: region.zone, year: scenarios.year, versions: scenarios.versions, summary: region.fleet.summary, units: region.fleet.units, unplaceable: region.fleet.unplaceable, recorded: region.fleet.recorded }));
      file(`${scenarioPath(region.ba)}fleet.csv`, fleetCsv(region));
    }
  }
  // The queue explorer, under whatever posture the captured terms give LBNL's file.
  const q = queuePages(join(ROOT, 'data'));
  if (q) {
    const qEntry = (await import(pathToFileURL(join(ROOT, 'pipeline/registry/lbnl-queued-up.mjs')).href)).default;
    const qPosture = qEntry.takedown ? 'link' : health?.datasets.find((d) => d.id === 'lbnl-queued-up')?.terms?.posture ?? postureOf(qEntry).posture;
    if (qPosture !== 'link') {
      write(queuePath(), queueIndexPage({ q, i18n, posture: qPosture }));
      for (const state of q.states) write(queuePath(state.state), queueStatePage({ q, state, i18n, posture: qPosture }));
      // The same summaries as JSON, one file per state, for the siting read-out
      // (siting/where-and-how-long). Summaries only: no project rows, so no point
      // of interconnection can travel with them.
      mkdirSync(join(outDir, 'queue'), { recursive: true });
      for (const state of q.states) {
        writeFileSync(join(outDir, `queue/${state.state.toLowerCase()}.json`), JSON.stringify(queueStateJson(q, state)));
      }
    }
  }
  // The on-device lookup: a prefix table, one shard per state, and which utilities have pages.
  const lookup = lookupData(join(ROOT, 'data'));
  if (lookup) {
    mkdirSync(join(outDir, 'lookup'), { recursive: true });
    writeFileSync(join(outDir, 'lookup/zip3.json'), JSON.stringify(lookup.zip3));
    for (const [st, s] of lookup.shards) writeFileSync(join(outDir, `lookup/${st}.json`), JSON.stringify(s));
    writeFileSync(join(outDir, 'lookup/pages.json'), JSON.stringify([...withPage].sort((a, b) => a - b)));
    write(LOOKUP_PATH, lookupPage({ i18n, sources: lookup.sources }));
    // The weather station picker finds the served GHCN-Daily version here; its shards are named by state only.
    if (lookup.sources.weather) {
      mkdirSync(join(outDir, 'weather'), { recursive: true });
      const w = lookup.sources.weather;
      writeFileSync(join(outDir, 'weather/meta.json'), JSON.stringify({ dataset: w.dataset, version: w.version, release: w.release ?? null, asOf: w.asOf, attribution: w.attribution }));
    }
  }
  // The command bar's index: tools, glossary terms, and every place with a page.
  // Written here because places need the entity data built above (design D7).
  const places = placeEntries({ regions, utilities, balancing, lookup, withPage });
  writeFileSync(join(outDir, 'command-index.json'), JSON.stringify([...buildCommandIndex(TOOLS, toolPath, GLOSSARY), ...places]) + '\n');

  // The bill check's tariff picker: each state's URDB residential rates, fetched only for the chosen utility's state.
  const tariffs = tariffData(join(ROOT, 'data'));
  if (tariffs) {
    mkdirSync(join(outDir, 'bills/tariffs'), { recursive: true });
    for (const [st, s] of tariffs.shards) writeFileSync(join(outDir, `bills/tariffs/${st}.json`), JSON.stringify(s));
  }
  // Form 1 revenue-requirement inputs by EIA utility id, latest year, for the explainer's prefill.
  const ferc1 = served(join(ROOT, 'data'), 'pudl-ferc1', 'revenue_inputs');
  if (ferc1) {
    const latest = Math.max(...ferc1.rows.map((r) => r.year));
    const byEia = {};
    for (const r of ferc1.rows) {
      if (r.year !== latest || !r.utility_ids_eia || r.rate_base === null) continue;
      for (const id of r.utility_ids_eia.split(' ')) byEia[id] = { name: r.utility_name_ferc1, year: r.year, om: (r.operation_expense ?? 0) + (r.maintenance_expense ?? 0), depreciation: (r.depreciation_expense ?? 0) + (r.amortization_expense ?? 0), otherTaxes: r.taxes_other_than_income ?? 0, rateBase: r.rate_base, adit: r.rate_base_net_adit, workingCapital: r.rate_base_working_capital, plantAndOther: r.rate_base_plant_and_other };
    }
    mkdirSync(join(outDir, 'bills'), { recursive: true });
    writeFileSync(join(outDir, 'bills/ferc1.json'), JSON.stringify({ release: ferc1.manifest.release ?? ferc1.manifest.version, asOf: ferc1.manifest.asOf, utilities: byEia }));
  }
  // County outage history from EAGLE-I, one file per state, for the backup power size.
  const outages = served(join(ROOT, 'data'), 'eaglei', 'events');
  if (outages) {
    const cov = served(join(ROOT, 'data'), 'eaglei', 'coverage').rows;
    const customers = Object.fromEntries(served(join(ROOT, 'data'), 'eaglei', 'counties').rows.map((r) => [r.fips, r.customers]));
    const [from, to] = outages.table.dataPeriod.split('-').map(Number);
    const byState = new Map();
    for (const e of outages.rows) {
      const st = byState.get(e.state) ?? byState.set(e.state, new Map()).get(e.state);
      (st.get(e.fips) ?? st.set(e.fips, []).get(e.fips)).push(e);
    }
    mkdirSync(join(outDir, 'outages'), { recursive: true });
    for (const [st, counties] of byState) {
      const coverage = Object.fromEntries(cov.filter((c) => c.state === st).map((c) => [c.year, c.max_pct_covered]));
      const summary = Object.fromEntries([...counties].map(([fips, events]) => [fips, { customers: customers[fips], ...countyHistory(events, coverage, { from, to }) }]));
      writeFileSync(join(outDir, `outages/${st}.json`), JSON.stringify({ release: outages.manifest.release, asOf: outages.manifest.asOf, from, to, coverage, counties: summary }));
    }
  }
  // Hourly carbon from EIA-930: every region's shards by year, and its typical hours for the cleanest-hours picker.
  const carbon = carbonData(join(ROOT, 'data'));
  if (carbon) {
    mkdirSync(join(outDir, 'carbon/typical'), { recursive: true });
    writeFileSync(join(outDir, 'carbon/regions.json'), JSON.stringify(carbon.regions));
    for (const [ba, typ] of carbon.typical) writeFileSync(join(outDir, `carbon/typical/${ba}.json`), JSON.stringify(typ));
  }
  // ERCOT's published 4CP intervals, for the workbench's coincident-peak panel.
  mkdirSync(join(outDir, 'bills'), { recursive: true });
  writeFileSync(join(outDir, 'bills/ercot-4cp.json'), readFileSync(join(ROOT, 'data/curated/ercot-4cp.json')));
  // The workbench's bill on a meter file: rates as tariff records, in buckets by utility id, so the
  // page fetches one bucket and keeps the rates of the utility it was asked for.
  const records = rateRecords(join(ROOT, 'data'));
  if (records) {
    mkdirSync(join(outDir, 'bills/rates'), { recursive: true });
    for (const [bucket, list] of [...records.byBucket].sort((a, b) => a[0] - b[0])) writeFileSync(join(outDir, `bills/rates/${bucket}.json`), JSON.stringify({ asOf: records.asOf, rates: list }));
  }
  for (const utility of utilities?.utilities ?? []) {
    if (!utility.page) continue;
    const nmUtility = netMetering?.utility(utility.id);
    const home = utility.homeState;
    write(utilityPath(utility.id), utilityPage({ utility, sources: utilities.sources, i18n, titleName: utilityNames.get(utility.id), plantHasPage: (id) => plantIds.has(id),
      extra: nmUtility ? netMeteringSection({ data: { ...nmUtility, states: nmUtility.states.length ? nmUtility.states : [home] }, nm: netMetering.manifest, i18n, regulator: regulatorOf(home), state: home, stateName: regulatorOf(home)?.stateName ?? home, stateLink: statePath(home), utility: utility.name }) : '' }));
  }
  write('/report/', reportPage({ i18n }));
  write('/404.html', notFoundPage({ tools: TOOLS, i18n }));
  const entries = new Map(await Promise.all(datasets.map(async (d) => [d.dataset, (await import(pathToFileURL(join(ROOT, 'pipeline/registry', `${d.dataset}.mjs`)).href)).default])));
  write(QF_PATH, qualifyingFacilityPage({ checklist: qfChecklist, i18n }));
  write(LEDGER_PATH, ledgerPage({ ledger, i18n }));
  writeFileSync(join(outDir, 'ledger/ledger.json'), JSON.stringify(ledger, null, 2) + '\n');
  const checks = consistencyChecks(join(ROOT, 'data'));
  write(CHECKS_PATH, checksPage({ checks, i18n }));
  writeFileSync(join(outDir, 'ledger/checks.json'), JSON.stringify(checks, null, 2) + '\n');

  const duplicates = [...titles].filter(([, paths]) => paths.length > 1);
  if (duplicates.length || tooLong.length) {
    throw new Error(`page metadata: ${[...duplicates.map(([t, p]) => `"${t}" is the title of ${p.join(', ')}`), ...tooLong].slice(0, 20).join('; ')}`);
  }

  // The states index, the catalog, and last the home page, which shows only cells whose page exists.
  if (regions) write(STATES_PATH, statesIndexPage({ i18n }));
  const datasetDate = (ids) => ids.map((id) => datasets.find((d) => d.dataset === id)?.asOf).filter(Boolean).sort().at(-1) ?? null;
  const exists = (p) => pages.includes(p.replace(/#.*$/, ''));
  // Section pages come after every page they may link, so a cell shows only once its page exists.
  for (const id of ['bills', 'data', 'carbon', 'grid', 'learn']) write(`/${id}/`, sectionPage({ id, tools: TOOLS, datasets, entries, i18n, exists, asOf: datasetDate }));
  write(CATALOG_PATH, catalogPage({ tools: TOOLS, i18n, exists, asOf: datasetDate }));
  write('/', homePage({ i18n }));
  // The simplicity budget: six sections at most, five cells a lane at most.
  const overBudget = checkSimplicity(SECTIONS);
  if (overBudget.length) throw new Error(`simplicity budget: ${overBudget.join('; ')}`);

  // Sitemaps: each page dated by the newest as-of date of the data it shows, or its tool version's date,
  // so a rebuild with unchanged data leaves every date as it was.
  const newestAsOf = (manifests) => Object.values(manifests ?? {}).filter(Boolean).reduce((m, x) => (x.asOf > m ? x.asOf : m), '0000-00-00');
  const toolDate = new Map(TOOLS.map(({ manifest: m }) => [m.id, changelog.find((c) => c.toolId === m.id && c.version === m.version)?.date ?? null]));
  const fallback = [...toolDate.values()].filter(Boolean).sort().at(-1) ?? buildDate.slice(0, 10);
  const datasetAsOf = new Map(datasets.map((d) => [d.dataset, d.asOf]));
  const familyDate = [['/plants/', plants && newestAsOf(plants.sources)], ['/utilities/', utilities && newestAsOf(utilities.sources)], ['/states/', regions && newestAsOf(regions.sources)],
    ['/subregions/', regions?.sources.egrid?.asOf], ['/queue/', q?.manifest.asOf], ['/lookup/', lookup && newestAsOf(lookup.sources)]];
  const lastmodOf = (path) => {
    const tool = TOOLS.find(({ manifest: m }) => path === toolPath(m.id) || path === `/methods/${m.id}/`);
    if (tool) return toolDate.get(tool.manifest.id) ?? fallback;
    const ds = /^\/data\/([a-z0-9-]+)\/$/.exec(path);
    if (ds && datasetAsOf.has(ds[1])) return datasetAsOf.get(ds[1]);
    return familyDate.find(([prefix, d]) => d && path.startsWith(prefix))?.[1] ?? fallback;
  };
  const listed = pages.filter((p) => p.endsWith('/')).map((p) => ({ path: p, lastmod: lastmodOf(p) }));
  for (const [file, xml] of Object.entries(sitemaps(listed, ORIGIN).files)) {
    mkdirSync(dirname(join(outDir, file)), { recursive: true });
    writeFileSync(join(outDir, file), xml);
  }
  writeFileSync(join(outDir, 'robots.txt'), robotsTxt(ORIGIN));

  // Atom feeds: the changelog, every dataset version, and corrections. Each feed's date is its newest entry's.
  mkdirSync(join(outDir, 'feeds'), { recursive: true });
  const feed = (name, title, page, entries) => writeFileSync(join(outDir, `feeds/${name}.xml`), atomFeed({ id: `${ORIGIN}/feeds/${name}.xml`, title, self: `${ORIGIN}/feeds/${name}.xml`, alternate: `${ORIGIN}${page}`, author: strings['site.name'], entries: entries.length ? entries : [], empty: fallback }));
  feed('changelog', strings['feeds.changelog'], '/changelog/', changelog.map((c) => ({
    id: `${ORIGIN}/changelog/#${c.toolId ?? 'site'}-${c.version}`, title: `${TOOLS.find((x) => x.manifest.id === c.toolId)?.manifest.title ?? c.toolId ?? strings['site.name']} ${c.version}`, updated: c.date, link: `${ORIGIN}/changelog/`, summary: c.reason,
  })));
  const releases = [];
  for (const d of datasets) {
    const versions = readdirSync(join(ROOT, 'data', d.dataset), { withFileTypes: true }).filter((x) => x.isDirectory() && /^\d{4}-\d{2}$/.test(x.name)).map((x) => x.name);
    const short = entries.get(d.dataset)?.shortTitle ?? d.title;
    for (const v of versions) {
      releases.push(releaseEntry(JSON.parse(readFileSync(join(ROOT, 'data', d.dataset, v, 'manifest.json'), 'utf8')), short, ORIGIN));
    }
  }
  feed('data', strings['feeds.data'], '/data/', releases);
  feed('corrections', strings['feeds.corrections'], '/corrections/', corrections.map((c, i) => ({ id: `${ORIGIN}/corrections/#${c.date}-${i}`, title: `${c.tier}: ${c.subject}`, updated: c.date, link: `${ORIGIN}/corrections/`, summary: c.cause })));

  writeFileSync(join(outDir, '_redirects'), redirectsFile(redirects));
  mkdirSync(join(outDir, '.well-known'), { recursive: true });
  writeFileSync(join(outDir, '.well-known/security.txt'), securityTxt(buildDate));

  // The inline theme script's hash, for the Worker's CSP (task 5.1).
  writeFileSync(join(outDir, '_csp-hashes.json'), JSON.stringify({ 'script-src': [`sha256-${createHash('sha256').update(THEME_SCRIPT).digest('base64')}`] }, null, 2) + '\n');

  cpSync(join(ROOT, 'site/icon.svg'), join(outDir, 'icon.svg'));
  writeFileSync(join(outDir, 'manifest.webmanifest'), JSON.stringify({
    name: strings['site.name'], short_name: strings['site.name'], description: strings['site.tagline'],
    start_url: '/', scope: '/', display: 'standalone', background_color: '#e9ebe8', theme_color: '#222624',
    icons: [{ src: '/icon.svg', sizes: 'any', type: 'image/svg+xml', purpose: 'any' }],
  }, null, 2) + '\n');

  // The service worker precaches the app shell and is versioned by the checksums of what it caches.
  // Dataset shards are cached as they are visited, not precached, so the shell stays small as data grows.
  // Entity pages (thousands of plants) are cached as visited too, not precached.
  // So are the lookup's state shards (2.4 MB in all) and the bill tools' rate files (about 50 MB): a visitor needs only their own utility's.
  const shell = walk(outDir).filter((f) => !f.startsWith('_') && !f.startsWith('data/') && !ENTITY_FAMILIES.some((d) => f.startsWith(d)) && !(f.startsWith('lookup/') && f.endsWith('.json') && f !== 'lookup/zip3.json') && !f.startsWith('bills/tariffs/') && !f.startsWith('bills/rates/') && !f.startsWith('outages/') && !f.startsWith('carbon/') && !f.startsWith('large-load/') && !f.startsWith('weather/') && !f.startsWith('site/cards/'));
  const version = sha256(shell.map((f) => `${f}:${sha256(readFileSync(join(outDir, f)))}`).join('\n')).slice(0, 12);
  const urls = shell.map((f) => `/${f.replace(/(^|\/)index\.html$/, '$1')}`);
  writeFileSync(join(outDir, 'sw.js'), serviceWorkerSource({ version, files: urls }));

  // The host serves everything in the deploy root, so the internal files are named here
  // instead: _redirects is the host's own, and it reads that itself.
  writeFileSync(join(outDir, '.assetsignore'), '_csp-hashes.json\n_manifest.json\n');
  const files = walk(outDir).filter((f) => f !== '_manifest.json');
  const manifest = files.map((f) => ({ path: f, sha256: sha256(readFileSync(join(outDir, f))) }));
  writeFileSync(join(outDir, '_manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
  return { outDir, pages, files: files.length + 1 };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const r = await build({ outDir: process.argv[2] });
  console.log(`built ${r.pages.length} pages, ${r.files} files in ${r.outDir}`);
}
