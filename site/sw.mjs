// The service worker, generated at build time (platform/app-shell, "Offline
// after first visit"). It precaches the app shell (pages, code, styles, the
// sample file) into a cache named for this build, serves it cache-first, and
// caches anything else it fetches (entity pages and data shards) as visited.

/**
 * @param {{version: string, files: string[]}} p
 * @returns {string} the service worker source
 */
export function serviceWorkerSource({ version, files }) {
  return `// Generated by site/build.mjs. Do not edit.
const SHELL = 'gridprims-shell-${version}';
const VISITED = 'gridprims-visited';
const FILES = ${JSON.stringify(files)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(SHELL).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => k.startsWith('gridprims-shell-') && k !== SHELL).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});

self.addEventListener('fetch', (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== 'GET' || url.origin !== self.location.origin || url.pathname.startsWith('/api/')) return;
  e.respondWith((async () => {
    const shell = await caches.open(SHELL);
    const hit = await shell.match(e.request, { ignoreSearch: true });
    if (hit) return hit;
    try {
      const res = await fetch(e.request);
      if (res.ok) (await caches.open(VISITED)).put(e.request, res.clone());
      return res;
    } catch (err) {
      const seen = await (await caches.open(VISITED)).match(e.request);
      if (seen) return seen;
      if (e.request.mode === 'navigate') return (await shell.match('/404.html')) ?? Response.error();
      throw err;
    }
  })());
});
`;
}
