// Writes core/tools/calc.energy-units.emissions/rates.mjs, the eGRID subregion
// output emission rates the emissions tool reads, from the served eGRID
// snapshot, so the tool stays data-free at run time. A test fails when the
// file drifts from the snapshot.
//   node verify/tools/egrid-rates.mjs > core/tools/calc.energy-units.emissions/rates.mjs

import { served } from '../../site/entities/plants.mjs';
import { join } from 'node:path';

const e = served(join(import.meta.dirname, '../../data'), 'egrid', 'subregions');
const rows = [...e.rows].sort((a, b) => a.subregion.localeCompare(b.subregion));
const line = (r) => `  ${r.subregion}: { name: ${JSON.stringify(r.subregion_name)}, co2: ${r.co2_rate_lb_mwh}, ch4: ${r.ch4_rate_lb_mwh}, n2o: ${r.n2o_rate_lb_mwh}, co2e: ${r.co2e_rate_lb_mwh} },`;
console.log(`// eGRID${rows[0].data_year} total output emission rates by subregion, in lb/MWh, from the
// served eGRID snapshot ${e.manifest.version} (${e.manifest.title}, ${e.manifest.publisher}).
// Generated by verify/tools/egrid-rates.mjs; do not edit by hand.

export const EDITION = { name: 'eGRID${rows[0].data_year}', dataYear: ${rows[0].data_year}, snapshot: '${e.manifest.version}', asOf: '${e.manifest.asOf}' };

export const RATES = {
${rows.map(line).join('\n')}
};`);
